import assert from 'node:assert/strict';
import type { TimelineItem } from '../editor/types';
import { pastedSpeechItems, pastedRecognitionJobs, pastedTimingSnapshot, applyPastedRecognition } from './pastedTranscriptWorkflow';
import { buildPastedTranscriptTrack } from './pastedTranscriptTrack';
import { basicCaptionPatch } from './basicCaptionStyle';
import { newManualCaptions } from './manualCaptions';

const clip: TimelineItem = { id: 'one', kind: 'audio', track: 'A1', src: '/media/uploads/voice.wav', name: '口播', startFrame: 0, durationInFrames: 30 };
const second = { ...clip, id: 'two', startFrame: 60 };
const bgm = { ...clip, id: 'music', name: 'BGM music', src: '/media/uploads/music.wav' };
const ready = { ...clip, id: 'ready', startFrame: 120, transcript: [{ text: '你好', start: 0, end: 1000 }] };
const items = [clip, second, bgm, ready];
const original = structuredClone(items);
assert.equal(pastedSpeechItems(items, 'A1').length, 3, 'unrecognized speech is selectable');
const jobs = pastedRecognitionJobs(pastedSpeechItems(items, 'A1'));
assert.equal(jobs.length, 1, 'split clips share one source recognition');
assert.deepEqual(jobs[0].clips.map((item) => item.id), ['one', 'two']);
assert.equal(pastedRecognitionJobs([ready]).length, 0, 'existing timings reused');
assert.equal(pastedRecognitionJobs([{ ...ready, transcriptStale: true }]).length, 1, 'stale timing is not reused');
assert.notEqual(pastedTimingSnapshot(items, 'A1'), pastedTimingSnapshot([{ ...clip, srcInFrame: 30 }, second, bgm, ready], 'A1'), 'trim edit invalidates pending alignment');
const timed = applyPastedRecognition(items, new Map(jobs[0].clips.map((item) => [item.id, ready.transcript])));
const stale = { ...ready, transcriptStale: true, srcInFrame: 9, deletedWordIdx: [0], silenceFrames: 0 };
const fresh = applyPastedRecognition([stale], new Map([[stale.id, ready.transcript]]))[0];
assert.deepEqual(fresh.deletedWordIdx, []); assert.equal(fresh.silenceFrames, undefined);
assert.equal(fresh.srcInFrame, 9, 'fresh ASR preserves the media trim actually used in preview');
assert.deepEqual(stale.deletedWordIdx, [0], 'old project edits are never reset by pasted ASR');
const built = buildPastedTranscriptTrack({ script: '你好。你好。你好。', items: timed, track: 'A1', fps: 30, laneId: 'new', label: '字幕' });
assert.equal(built.captions.sourceEntries?.[0].words?.length, 3);
assert.equal(built.captions.styleOverride?.color, '#ffffff');
assert.equal(built.captions.styleOverride?.strokeColor, '#000000');
assert.deepEqual(items, original, 'recognition for pasted captions never resets source edits');
const manual = newManualCaptions();
assert.equal(manual.motionPreset, 'none'); assert.equal(manual.pacing, 'phrase');
assert.equal(manual.styleOverride?.strokeWidth, 4);
const customized = { ...manual, sourceEntries: [{ id: 'old', itemId: 'manual:old', words: [{ text: 'test', start: 100, end: 500 }], style: { color: '#ff0000' } }] };
const simplified = basicCaptionPatch(customized);
assert.equal(simplified.sourceEntries?.[0].style, undefined);
assert.deepEqual(simplified.sourceEntries?.[0].words, customized.sourceEntries[0].words);
console.log('pastedTranscriptWorkflow.verify: selectable speech, deduplicated ASR, stale/edit guards, unchanged sources and simple captions passed');

import assert from 'node:assert/strict';
import { mkdtemp, readFile, writeFile, mkdir, rename } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join, relative } from 'node:path';
import { readVerificationReport, writeVerificationReport } from './verification-report.mjs';
const root = await mkdtemp(join(tmpdir(), 'zuoren-report-regression-'));
const file = join(root, 'results.json');
await writeVerificationReport(file, { results: ['failed'] });
await writeVerificationReport(file, { results: ['failed', 'passed'] });
assert.deepEqual(await readVerificationReport(file), { results: ['failed', 'passed'] });
assert.deepEqual(JSON.parse(await readFile(`${file}.previous`, 'utf8')), { results: ['failed'] });
await writeFile(file, Buffer.alloc(20));
assert.deepEqual(await readVerificationReport(file), { results: ['failed'], recoveredPreviousSnapshot: true });
await writeVerificationReport(file, { results: ['failed', 'retry'] });
assert.deepEqual(JSON.parse(await readFile(`${file}.previous`, 'utf8')), { results: ['failed'] }, 'corruption never replaces a validated backup');
await assert.rejects(writeVerificationReport(file, undefined), /serializable/);
assert.deepEqual(await readVerificationReport(file), { results: ['failed', 'retry'] });
const concurrent = join(root, 'concurrent.json');
await writeVerificationReport(concurrent, { stage: -1 });
const writes = Array.from({ length: 48 }, (_, stage) => writeVerificationReport(
  stage % 2 ? relative(process.cwd(), concurrent) : concurrent,
  { stage, payload: 'x'.repeat(8192), results: ['original failure', `sample ${stage}`] }));
await Promise.all(writes);
assert.equal((await readVerificationReport(concurrent)).stage, 47, 'Same-file writers commit in invocation order');
assert.equal(JSON.parse(await readFile(`${concurrent}.previous`, 'utf8')).stage, 46, 'Backup is the immediately previous complete snapshot');
const mutable = { stage: 48, results: ['failed'] };
const captured = writeVerificationReport(concurrent, mutable);
mutable.results.push('mutation after call');
await captured;
assert.deepEqual((await readVerificationReport(concurrent)).results, ['failed'], 'Queued writer captures evidence at invocation');
await assert.rejects(writeVerificationReport(concurrent, { circular: mutable, toJSON() { throw new Error('bad serialization'); } }), /bad serialization/);
await writeVerificationReport(concurrent, { stage: 49 });
assert.equal((await readVerificationReport(concurrent)).stage, 49);
const blocked = join(root, 'blocked.json');
await writeVerificationReport(blocked, { stage: 0 });
await mkdir(`${blocked}.previous`);
await assert.rejects(writeVerificationReport(blocked, { stage: 1 }));
assert.equal((await readVerificationReport(blocked)).stage, 0, 'Failed replacement retains the original report');
await rename(`${blocked}.previous`, `${blocked}.previous-blocked`);
await writeVerificationReport(blocked, { stage: 2 });
assert.equal((await readVerificationReport(blocked)).stage, 2, 'Failed operation does not poison later writes');
assert.equal(JSON.parse(await readFile(`${blocked}.previous`, 'utf8')).stage, 0);
console.log('verification report: ordered concurrent snapshots, preserved failures, failed-write recovery and corruption recovery passed');
